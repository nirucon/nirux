#!/usr/bin/env python3
"""Generate the short NIRUX system sounds (feedback, power, devices, security,
dictation).

The sounds are synthesised from scratch, deterministically, with the Python
standard library only. ffmpeg (with libvorbis) encodes them to Ogg Vorbis.
Run it from anywhere:

    python3 tools/gen-sounds.py            # write sounds/*.ogg and sounds/levels/*.ogg
    python3 tools/gen-sounds.py --report   # also print duration, peak and loudness
    python3 tools/gen-sounds.py --wav DIR  # write 16-bit WAV files to DIR instead

One family, one key. The long sounds (startup, notification, update) sit on
G and C: the notification is an almost pure G4 + D5 fifth. Every sound here
uses the G major pentatonic set (G A B D E) and the same voice: a soft
attack, a near-sine fundamental with a quieter, faster-decaying fourth
partial (a marimba bar) and, for the glassy sounds, a faint inharmonic
2.76 partial. Nothing starts with silence; every sound fades to true zero.

Loudness is normalised to a per-sound target in LUFS (maximum momentary,
EBU R128 K-weighting, 400 ms windows). The reference is the notification at
about -11.7 LUFS-M; feedback ticks sit well below it so that a held volume
key never becomes louder than a message.

The sounds are original work generated by this script and are released
under the repository's MIT license.
"""

import argparse
import math
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import wave

RATE = 44100
PEAK_CEILING_DB = -3.0

# Equal temperament, A4 = 440 Hz.
NOTE = {
    "G3": 196.00, "B3": 246.94, "D4": 293.66, "E4": 329.63, "G4": 392.00,
    "A4": 440.00, "B4": 493.88, "D5": 587.33, "E5": 659.26, "G5": 783.99,
    "A5": 880.00, "B5": 987.77, "D6": 1174.66, "E6": 1318.51, "G6": 1567.98,
    "B6": 1975.53,
}


def silence(seconds):
    return [0.0] * int(round(seconds * RATE))


def mix(base, other, at=0.0, gain=1.0):
    """Add OTHER into BASE starting AT seconds, growing BASE as needed."""
    start = int(round(at * RATE))
    end = start + len(other)
    if end > len(base):
        base.extend([0.0] * (end - len(base)))
    for i, v in enumerate(other):
        base[start + i] += v * gain
    return base


def envelope(n, attack, tau):
    """Raised-cosine attack, then exponential decay with time constant TAU."""
    a = max(1, int(attack * RATE))
    out = []
    for i in range(n):
        t = i / RATE
        if i < a:
            g = 0.5 - 0.5 * math.cos(math.pi * i / a)
        else:
            g = math.exp(-(t - attack) / tau)
        out.append(g)
    return out


def bar(freq, length, tau, attack=0.002, fourth=0.18, glass=0.0, glide=0.0,
        drop=0.0):
    """One struck bar: fundamental, a 4.0 partial and an optional 2.76 one.

    GLIDE bends the pitch by that many cents over the note; DROP bends it
    down by that many cents with a fast (20 ms) settle, as a soft thud does.
    """
    n = int(round(length * RATE))
    env = envelope(n, attack, tau)
    env4 = envelope(n, attack, tau / 3.2)
    env2 = envelope(n, attack, tau / 2.0)
    out = []
    phase = phase4 = phase2 = 0.0
    for i in range(n):
        t = i / RATE
        cents = glide * (t / length)
        if drop:
            cents -= drop * (1.0 - math.exp(-t / 0.020))
        f = freq * 2 ** (cents / 1200.0)
        phase += 2 * math.pi * f / RATE
        phase4 += 2 * math.pi * f * 4.0 / RATE
        phase2 += 2 * math.pi * f * 2.76 / RATE
        v = math.sin(phase) * env[i]
        v += fourth * math.sin(phase4) * env4[i]
        if glass:
            v += glass * math.sin(phase2) * env2[i]
        out.append(v)
    return out


class Noise:
    """A deterministic white-noise source (32-bit LCG)."""

    def __init__(self, seed):
        self.state = seed & 0xFFFFFFFF

    def next(self):
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return self.state / 2147483648.0 - 1.0


def biquad(samples, kind, freq, q=0.707):
    """RBJ cookbook low-pass, high-pass or band-pass filter."""
    w = 2 * math.pi * freq / RATE
    alpha = math.sin(w) / (2 * q)
    cw = math.cos(w)
    if kind == "low":
        b = [(1 - cw) / 2, 1 - cw, (1 - cw) / 2]
    elif kind == "high":
        b = [(1 + cw) / 2, -(1 + cw), (1 + cw) / 2]
    else:  # band, constant 0 dB peak gain
        b = [alpha, 0.0, -alpha]
    a = [1 + alpha, -2 * cw, 1 - alpha]
    b = [x / a[0] for x in b]
    a1, a2 = a[1] / a[0], a[2] / a[0]
    x1 = x2 = y1 = y2 = 0.0
    out = []
    for x in samples:
        y = b[0] * x + b[1] * x1 + b[2] * x2 - a1 * y1 - a2 * y2
        x2, x1, y2, y1 = x1, x, y1, y
        out.append(y)
    return out


def burst(seed, length, tau, attack=0.0005):
    n = int(round(length * RATE))
    src = Noise(seed)
    env = envelope(n, attack, tau)
    return [src.next() * env[i] for i in range(n)]


def finish(samples, fade=0.006):
    """Trim the inaudible tail, then fade the last FADE seconds to zero."""
    peak = max(abs(v) for v in samples) or 1.0
    floor = peak * 10 ** (-62 / 20)
    end = len(samples)
    while end > 0 and abs(samples[end - 1]) < floor:
        end -= 1
    samples = samples[:end]
    f = min(len(samples), int(fade * RATE))
    for i in range(f):
        samples[len(samples) - f + i] *= 0.5 + 0.5 * math.cos(math.pi * (i + 1) / f)
    if samples:
        samples[-1] = 0.0
    return samples


# --- loudness ---------------------------------------------------------------

def k_weight(samples):
    """ITU-R BS.1770 K-weighting for RATE (coefficients as in libebur128)."""
    f0, gain, q = 1681.974450955533, 3.999843853973347, 0.7071752369554196
    k = math.tan(math.pi * f0 / RATE)
    vh = 10 ** (gain / 20.0)
    vb = vh ** 0.4996667741545416
    a0 = 1.0 + k / q + k * k
    s1b = [(vh + vb * k / q + k * k) / a0, 2.0 * (k * k - vh) / a0,
           (vh - vb * k / q + k * k) / a0]
    s1a = [2.0 * (k * k - 1.0) / a0, (1.0 - k / q + k * k) / a0]
    f0, q = 38.13547087602444, 0.5003270373238773
    k = math.tan(math.pi * f0 / RATE)
    a0 = 1.0 + k / q + k * k
    s2b = [1.0, -2.0, 1.0]
    s2a = [2.0 * (k * k - 1.0) / a0, (1.0 - k / q + k * k) / a0]
    out = samples
    for b, a in ((s1b, s1a), (s2b, s2a)):
        x1 = x2 = y1 = y2 = 0.0
        stage = []
        for x in out:
            y = b[0] * x + b[1] * x1 + b[2] * x2 - a[0] * y1 - a[1] * y2
            x2, x1, y2, y1 = x1, x, y1, y
            stage.append(y)
        out = stage
    return out


def momentary_max(samples):
    """Maximum momentary loudness (400 ms windows, 10 ms hop) in LUFS."""
    weighted = k_weight(samples + [0.0] * int(0.4 * RATE))
    win = int(0.4 * RATE)
    hop = int(0.01 * RATE)
    best = 1e-12
    acc = sum(v * v for v in weighted[:win])
    pos = 0
    while True:
        best = max(best, acc / win)
        nxt = pos + hop
        if nxt + win > len(weighted):
            break
        acc -= sum(v * v for v in weighted[pos:nxt])
        acc += sum(v * v for v in weighted[pos + win:nxt + win])
        pos = nxt
    return -0.691 + 10 * math.log10(best)


def normalise(samples, target_lufs):
    lufs = momentary_max(samples)
    gain = 10 ** ((target_lufs - lufs) / 20.0)
    peak = max(abs(v) for v in samples) * gain
    ceiling = 10 ** (PEAK_CEILING_DB / 20.0)
    if peak > ceiling:
        gain *= ceiling / peak
    return [v * gain for v in samples]


# --- the sounds --------------------------------------------------------------

def tock(freq, direction):
    """The volume tick: a 40 ms wooden marimba tock."""
    glide = 22.0 * direction
    fourth = 0.20 if direction > 0 else 0.12
    body = bar(freq, 0.040, 0.010, attack=0.0012, fourth=fourth, glide=glide)
    click = biquad(burst(11 if direction > 0 else 13, 0.004, 0.0008), "band", 2.4 * freq, 1.2)
    return finish(mix(body, click, gain=0.10), fade=0.004)


def volume_pitch(level):
    """D5 at 0 %, G5 at 100 %: five semitones across the whole range."""
    return NOTE["D5"] * 2 ** ((5.0 * level / 100.0) / 12.0)


def volume_limit():
    body = bar(NOTE["G4"], 0.062, 0.017, attack=0.004, fourth=0.05, drop=45.0)
    return finish(biquad(body, "low", 1800.0), fade=0.008)


def two_notes(first, second, gap, length, tau, fourth=0.18, glass=0.0, second_gain=0.9):
    out = bar(first, length, tau, fourth=fourth, glass=glass)
    mix(out, bar(second, length, tau, fourth=fourth, glass=glass), at=gap, gain=second_gain)
    return finish(out)


def mute():
    return two_notes(NOTE["B4"], NOTE["G4"], 0.058, 0.092, 0.022, fourth=0.14)


def unmute():
    return two_notes(NOTE["G4"], NOTE["B4"], 0.058, 0.092, 0.022, fourth=0.14)


def airy(freq, seed):
    n = 0.030
    hiss = biquad(biquad(burst(seed, n, 0.006, attack=0.0015), "high", 4500.0), "band", 7000.0, 0.9)
    tone = bar(freq, n, 0.008, attack=0.0015, fourth=0.0, glass=0.0)
    return finish(mix(tone, hiss, gain=0.9), fade=0.004)


def power(up):
    a, b = (NOTE["G4"], NOTE["D5"]) if up else (NOTE["D5"], NOTE["G4"])
    return two_notes(a, b, 0.095, 0.24, 0.060, fourth=0.16, glass=0.05)


def arpeggio(notes, step, length, tau, fourth=0.16, glass=0.05, decay=1.0):
    out = []
    for i, name in enumerate(notes):
        mix(out, bar(NOTE[name], length, tau, fourth=fourth, glass=glass), at=i * step, gain=decay ** i)
    return finish(out)


def battery_low():
    return arpeggio(["D5", "B4", "G4"], 0.115, 0.26, 0.070, decay=0.92)


def battery_critical():
    out = []
    for rep in range(2):
        at = rep * 0.34
        mix(out, bar(NOTE["B4"], 0.20, 0.050, fourth=0.24, glass=0.06), at=at)
        mix(out, bar(NOTE["E4"], 0.26, 0.065, fourth=0.24, glass=0.06), at=at + 0.11, gain=0.95)
    return finish(out)


def battery_full():
    return arpeggio(["G4", "B4", "D5", "G5"], 0.080, 0.30, 0.080, decay=0.9)


def click(freq, seed):
    """A small plastic click: a band-passed transient with a glassy ring."""
    tick = biquad(burst(seed, 0.012, 0.0015), "band", 3200.0, 1.4)
    ring = bar(freq, 0.060, 0.014, attack=0.0008, fourth=0.0, glass=0.32)
    return mix(ring, tick, gain=0.55)


def device(up):
    a, b = (NOTE["A5"], NOTE["D6"]) if up else (NOTE["D6"], NOTE["A5"])
    out = click(a, 21)
    mix(out, click(b, 22), at=0.072, gain=0.92)
    return finish(out)


def screenshot():
    first = biquad(biquad(burst(31, 0.040, 0.007), "low", 2600.0), "high", 300.0)
    second = biquad(biquad(burst(32, 0.050, 0.010), "low", 2000.0), "high", 250.0)
    body = bar(NOTE["B5"] / 2, 0.050, 0.012, attack=0.001, fourth=0.0)
    out = mix(list(first), body, gain=0.35)
    mix(out, second, at=0.062, gain=0.8)
    mix(out, bar(NOTE["G4"], 0.050, 0.012, attack=0.001, fourth=0.0), at=0.062, gain=0.25)
    return finish(out)


def auth_fail():
    thud = bar(NOTE["G3"], 0.15, 0.040, attack=0.003, fourth=0.04, drop=120.0)
    under = bar(NOTE["G3"] / 2, 0.15, 0.045, attack=0.004, fourth=0.0)
    knock = biquad(burst(41, 0.03, 0.006, attack=0.001), "low", 700.0)
    out = mix(thud, under, gain=0.45)
    mix(out, knock, gain=0.25)
    return finish(biquad(out, "low", 1200.0), fade=0.012)


def lock():
    out = bar(NOTE["D6"], 0.32, 0.085, attack=0.004, fourth=0.0, glass=0.10)
    mix(out, bar(NOTE["G6"], 0.32, 0.075, attack=0.004, fourth=0.0, glass=0.08), gain=0.6)
    return finish(out)


def unlock():
    return two_notes(NOTE["G5"], NOTE["D6"], 0.070, 0.26, 0.070, fourth=0.0, glass=0.10)


def dictation(up):
    """Dictation start (D5 -> G5, "listening") and stop (G5 -> D5): two quick
    glassy bars, short enough to be over before the first word."""
    a, b = (NOTE["D5"], NOTE["G5"]) if up else (NOTE["G5"], NOTE["D5"])
    return two_notes(a, b, 0.055, 0.13, 0.032, fourth=0.10, glass=0.08, second_gain=0.85)


def dictation_done():
    """The text is in place: one soft high bar with a faint upper fifth."""
    out = bar(NOTE["B5"], 0.16, 0.040, attack=0.002, fourth=0.0, glass=0.12)
    mix(out, bar(NOTE["E6"], 0.14, 0.030, attack=0.002, fourth=0.0, glass=0.08), at=0.018, gain=0.35)
    return finish(out)


def dictation_error():
    """Nothing could be written: a falling B4 -> E4, darker than auth-fail's
    thud so the two are not confused."""
    out = two_notes(NOTE["B4"], NOTE["E4"], 0.075, 0.17, 0.045, fourth=0.22, glass=0.04)
    return finish(biquad(out, "low", 2200.0), fade=0.010)


# name -> (builder, target LUFS-M). The reference notification is ~-11.7.
SOUNDS = {
    "volume-up": (lambda: tock(volume_pitch(40), 1), -25.0),
    "volume-down": (lambda: tock(volume_pitch(40), -1), -25.0),
    "volume-limit": (volume_limit, -25.0),
    "mute": (mute, -22.0),
    "unmute": (unmute, -22.0),
    "brightness-up": (lambda: airy(NOTE["B6"], 51), -29.0),
    "brightness-down": (lambda: airy(NOTE["G6"], 52), -29.0),
    "power-plug": (lambda: power(True), -18.0),
    "power-unplug": (lambda: power(False), -18.0),
    "battery-low": (battery_low, -17.0),
    "battery-critical": (battery_critical, -15.0),
    "battery-full": (battery_full, -18.0),
    "device-connect": (lambda: device(True), -20.0),
    "device-disconnect": (lambda: device(False), -20.0),
    "screenshot": (screenshot, -21.0),
    "auth-fail": (auth_fail, -19.0),
    "lock": (lock, -27.0),
    "unlock": (unlock, -27.0),
    "dictation-start": (lambda: dictation(True), -23.0),
    "dictation-stop": (lambda: dictation(False), -23.0),
    "dictation-done": (dictation_done, -26.0),
    "dictation-error": (dictation_error, -21.0),
}

# The volume tick follows the new level: levels/volume-up-NNN.ogg for every
# 10 % step. nirunotify picks the nearest one; the plain file is the 40 % one
# (E5, in key).
LEVELS = range(0, 101, 10)


def all_sounds():
    for name, (build, target) in SOUNDS.items():
        yield name, normalise(build(), target)
    for direction, label in ((1, "up"), (-1, "down")):
        target = SOUNDS["volume-" + label][1]
        for level in LEVELS:
            yield "levels/volume-%s-%03d" % (label, level), normalise(
                tock(volume_pitch(level), direction), target)


def write_wav(path, samples):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(RATE)
        frames = b"".join(struct.pack("<h", max(-32767, min(32767, int(round(v * 32767))))) for v in samples)
        out.writeframes(frames)


def encode(wav, ogg):
    os.makedirs(os.path.dirname(ogg), exist_ok=True)
    subprocess.run([
        "ffmpeg", "-v", "error", "-y", "-i", wav,
        "-map_metadata", "-1", "-c:a", "libvorbis", "-q:a", "6",
        "-fflags", "+bitexact", "-flags:a", "+bitexact", "-serial_offset", "0", ogg,
    ], check=True)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", default=os.path.join(here, "..", "sounds"),
                        help="output directory (default: the repository's sounds/)")
    parser.add_argument("--wav", metavar="DIR", help="write WAV files to DIR and do not encode")
    parser.add_argument("--report", action="store_true", help="print duration, peak and loudness")
    args = parser.parse_args()
    if not args.wav and not shutil.which("ffmpeg"):
        sys.exit("gen-sounds: ffmpeg with libvorbis is needed to encode (or use --wav DIR)")
    tmp = tempfile.mkdtemp(prefix="nirux-sounds.")
    try:
        if args.report:
            print("%-26s %8s %8s %9s" % ("sound", "ms", "peak dB", "LUFS-M"))
        for name, samples in all_sounds():
            if args.wav:
                write_wav(os.path.join(args.wav, name + ".wav"), samples)
            else:
                wav = os.path.join(tmp, name + ".wav")
                write_wav(wav, samples)
                encode(wav, os.path.join(args.out, name + ".ogg"))
            if args.report:
                peak = max(abs(v) for v in samples)
                print("%-26s %8.0f %8.1f %9.1f" % (name, 1000.0 * len(samples) / RATE,
                                                  20 * math.log10(peak), momentary_max(samples)))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
