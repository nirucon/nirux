localsend_write_desktop() {
  mkdir -p "$PREFIX/share/applications" || die 'could not create the application directory'
  cat > "$WORK/localsend.desktop" <<EOF
# NIRUX owner: $PREFIX
[Desktop Entry]
Type=Application
Name=LocalSend
Comment=Share files with nearby devices
Exec=$BIN/localsend
Icon=$PREFIX/share/icons/hicolor/256x256/apps/localsend.png
Terminal=false
Categories=Network;FileTransfer;
StartupWMClass=localsend_app
EOF
  install -m 644 "$WORK/localsend.desktop" "$PREFIX/share/applications/localsend.desktop" || \
    die 'could not install the LocalSend desktop entry'
}

localsend_install() {
  # LocalSend is a large external application, like Helium. It is installed
  # from the official verified tarball, not Flatpak or AppImage.
  [ "${NIRUX_TEST_AS_ROOT:-0}" = 1 ] && return 0
  ls_installed=
  [ ! -x "$STATE/localsend/current/localsend_app" ] || ls_installed=$(localsend_installed_version || :)
  [ -n "${WORK:-}" ] || die 'LocalSend installation requires a working directory'
  mkdir -p "$WORK/download/localsend" || die 'could not create the LocalSend download directory'
  if app_upstream localsend "$LOCALSEND_VERSION" &&
     { [ -z "$ls_installed" ] || ! version_at_least "$ls_installed" "$AL_VERSION"; }; then
    ls_up=$AL_VERSION
    ls_archive=$WORK/download/localsend/LocalSend-$ls_up-linux-x86-64.tar.gz
    say "Downloading LocalSend $ls_up (newest upstream release)"
    if fetch "https://github.com/localsend/localsend/releases/download/v$ls_up/LocalSend-$ls_up-linux-x86-64.tar.gz" "$ls_archive" &&
       app_digest_ok "$ls_archive" "$AL_DIGEST" &&
       ( SUDO_SECRET_BORROWED=1; localsend_install_archive "$ls_archive" "$ls_up" ); then
      return 0
    fi
    say "nirux: LocalSend $ls_up could not be downloaded or verified; using the pinned version instead." >&2
  fi
  if [ -n "$ls_installed" ] && version_at_least "$ls_installed" "$LOCALSEND_VERSION"; then
    mkdir -p "$BIN" || die 'could not create the command directory'
    ln -sfn "$STATE/localsend/current/localsend_app" "$BIN/localsend" || die 'could not link LocalSend'
    localsend_write_desktop
    say "Managed LocalSend $ls_installed is already installed"
    return 0
  fi
  archive=$WORK/download/localsend/LocalSend-$LOCALSEND_VERSION-linux-x86-64.tar.gz
  say "Downloading LocalSend $LOCALSEND_VERSION"
  fetch "https://github.com/localsend/localsend/releases/download/v$LOCALSEND_VERSION/LocalSend-$LOCALSEND_VERSION-linux-x86-64.tar.gz" "$archive"
  actual=$(sha256sum "$archive" | cut -d ' ' -f1)
  [ "$actual" = "$LOCALSEND_SHA256" ] || die 'LocalSend checksum mismatch; current installation kept'
  localsend_install_archive "$archive" "$LOCALSEND_VERSION"
}
# Install a verified LocalSend ARCHIVE of VERSION.
localsend_install_archive() {
  archive=$1 ls_version=$2
  unpack=$WORK/localsend-unpack
  rm -rf "$unpack"
  mkdir -p "$unpack" || die 'could not create the LocalSend extraction directory'
  tar -xzf "$archive" -C "$unpack" || die 'could not extract the LocalSend archive'
  [ -x "$unpack/localsend_app" ] || die 'LocalSend archive is missing the executable'
  load_output=$(LD_TRACE_LOADED_OBJECTS=1 "$unpack/localsend_app" 2>&1 || :)
  missing_libs=$(printf '%s\n' "$load_output" | awk '/not found/ {print $1}' | sort -u)
  [ -z "$missing_libs" ] || die "LocalSend needs missing shared libraries: $(printf '%s' "$missing_libs" | tr '\n' ' ')"
  destination=$STATE/localsend/$ls_version
  staging=$STATE/localsend/.$ls_version.$$
  mkdir -p "$STATE/localsend" || die 'could not create the LocalSend directory'
  rm -rf "$staging"
  mv "$unpack" "$staging" || die 'could not stage the LocalSend files'
  rm -rf "$destination"
  mv "$staging" "$destination" || die 'could not install the LocalSend files'
  rm -f "$STATE/localsend/current"
  ln -s "$destination" "$STATE/localsend/current" || die 'could not activate LocalSend'
  mkdir -p "$BIN" || die 'could not create the command directory'
  ln -sfn "$STATE/localsend/current/localsend_app" "$BIN/localsend" || die 'could not link LocalSend'
  mkdir -p "$PREFIX/share/icons/hicolor/256x256/apps" || die 'could not create the icon directory'
  icon=$destination/data/flutter_assets/assets/img/logo-256.png
  if [ -f "$icon" ]; then
    install -m 644 "$icon" "$PREFIX/share/icons/hicolor/256x256/apps/localsend.png" || :
  fi
  printf '%s\n' "$ls_version" > "$STATE/localsend-version"
  app_prune_versions "$STATE/localsend" "$destination" LocalSend "$ls_version"
  localsend_write_desktop
  say "Installed managed LocalSend $ls_version"
}

localsend_remove_managed() {
  managed=0
  if [ -L "$BIN/localsend" ]; then
    case "$(readlink "$BIN/localsend")" in
      "$STATE/localsend/current/localsend_app"|"$STATE/localsend"/*) managed=1; rm -f "$BIN/localsend" ;;
    esac
  fi
  if [ "$managed" = 1 ] || [ -f "$STATE/localsend-version" ]; then
    rm -f "$PREFIX/share/applications/localsend.desktop" \
      "$PREFIX/share/icons/hicolor/256x256/apps/localsend.png"
  fi
  rm -f "$STATE/localsend-version"
  rm -rf "$STATE/localsend"
}

