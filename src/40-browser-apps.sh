status() {
  say "browser addon: $(browser_addon_policy)"
  if browser_path >/dev/null 2>&1; then say "Helium: $(browser_path)"; else say 'Helium: not installed'; fi
  if [ -f "$BROWSER_ADDON_POLICY" ]; then say "policy: $BROWSER_ADDON_POLICY"; else say 'policy: not installed'; fi
  [ ! -f "$STATE/browser-presets/bonjourr-nirux.json" ] || say "preset: $STATE/browser-presets/bonjourr-nirux.json"
}

browser_policy() {
  [ -f "$STATE/browser-policy" ] || { say keep; return 0; }
  policy=$(awk '$1 == "browser" && ($2 == "helium" || $2 == "none") {print $2; exit}' "$STATE/browser-policy")
  [ -n "$policy" ] || policy=keep
  say "$policy"
}
browser_policy_set() {
  mkdir -p "$STATE"
  printf '# NIRUX owner: %s\nbrowser %s\n' "$PREFIX" "$1" > "$STATE/.browser-policy.$$" || \
    die 'could not stage the browser policy'
  mv -f "$STATE/.browser-policy.$$" "$STATE/browser-policy" || \
    die 'could not persist the browser policy'
}
# $BIN/helium is a small NIRUX launcher (0.12.271) that adds the hardware video
# flags from $STATE/helium-flags; earlier releases linked the executable directly,
# and such a link is still recognised until the next install replaces it.
browser_launcher_owned() {
  [ -f "$1" ] && [ ! -L "$1" ] && owned "$1" && grep -qx '# NIRUX managed Helium launcher' "$1" 2>/dev/null
}
browser_managed() {
  if [ -L "$BIN/helium" ]; then
    [ "$(readlink "$BIN/helium")" = "$STATE/browser-current/helium" ]
    return
  fi
  browser_launcher_owned "$BIN/helium"
}
# The launcher reads $STATE/helium-flags when Helium starts: "arg VALUE" lines are
# passed before the user's own arguments (so a flag the user gives wins) and
# "env NAME=VALUE" lines set one of a few known variables. A missing or empty
# file starts Helium exactly as upstream does.
browser_write_launcher() {
  mkdir -p "$BIN" "$WORK" || die 'could not create the command directory'
  cat > "$WORK/helium-launcher" <<EOF
#!/bin/sh
# NIRUX owner: $PREFIX
# NIRUX managed Helium launcher
# Generated by nirux; replaced on every install and update. Flags: $STATE/helium-flags
flags='$STATE/helium-flags'
pci='${NIRUX_SYSFS_PCI:-/sys/bus/pci/devices}'
EOF
  cat >> "$WORK/helium-launcher" <<'EOF'
# The flags name the GPU (PCI address) they were verified for; when it is gone
# they are ignored, and its render node is looked up at every start.
gpu=; node=; use=1
if [ -r "$flags" ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in 'gpu '?*) gpu=${line#gpu }; break ;; esac
  done < "$flags"
  if [ -n "$gpu" ]; then
    use=0
    for r in "$pci/$gpu/drm"/renderD*; do
      if [ -e "$r" ]; then node=/dev/dri/${r##*/}; use=1; break; fi
    done
  fi
fi
if [ "$use" = 1 ] && [ -r "$flags" ]; then
  n=$#
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      'arg --'?*) set -- "$@" "${line#arg }" ;;
      node) [ -z "$node" ] || set -- "$@" "--render-node-override=$node" ;;
      'env MESA_VK_DEVICE_SELECT='*|'env LIBVA_DRIVER_NAME='*|'env NVD_BACKEND='*)
        export "${line#env }" ;;
    esac
  done < "$flags"
  # Move the user's arguments behind the flags.
  while [ "$n" -gt 0 ]; do set -- "$@" "$1"; shift; n=$((n - 1)); done
fi
EOF
  say "exec '$STATE/browser-current/helium' \"\$@\"" >> "$WORK/helium-launcher"
  if [ -f "$BIN/helium" ] && [ ! -L "$BIN/helium" ] && same_file "$WORK/helium-launcher" "$BIN/helium"; then
    return 0
  fi
  install -m 755 "$WORK/helium-launcher" "$BIN/.helium.$$" || die 'could not write the Helium launcher'
  mv -f "$BIN/.helium.$$" "$BIN/helium" || die 'could not activate the Helium command'
}
browser_unmanaged() {
  if [ -e "$BIN/helium" ] && ! browser_managed; then say "$BIN/helium"; return 0; fi
  path=$(command -v helium 2>/dev/null || :)
  if [ -n "$path" ] && [ "$path" != "$BIN/helium" ] && [ -x "$path" ]; then say "$path"; return 0; fi
  return 1
}
browser_path() {
  if browser_managed; then say "$BIN/helium"; return 0; fi
  browser_unmanaged
}
browser_installed_version() {
  [ -x "$BIN/helium" ] || return 1
  "$BIN/helium" --version 2>/dev/null | sed -n 's/^Helium \([0-9][0-9.]*\).*/\1/p' | head -n 1
}
write_prefix_file() {
  target=$1; source=$2
  if [ -f "$target" ]; then
    installed_sum=$(sha256sum "$target" | cut -d ' ' -f1)
    source_sum=$(sha256sum "$source" | cut -d ' ' -f1)
    [ "$installed_sum" != "$source_sum" ] || return 0
  fi
  if [ -f "$target" ] && ! owned "$target"; then
    [ -f "$target.nirux-backup" ] || cp -p "$target" "$target.nirux-backup" || \
      die "could not back up $target"
  fi
  mkdir -p "$(dirname "$target")" || die "could not create $(dirname "$target")"
  install -m 644 "$source" "$target" || die "could not install $target"
}
remove_prefix_file() {
  if [ -f "$1" ] && owned "$1"; then
    if [ -f "$1.nirux-backup" ]; then mv -f "$1.nirux-backup" "$1"
    else rm -f "$1"
    fi
  fi
}
browser_desktop_file() {
  say "$PREFIX/share/applications/helium.desktop"
}
browser_write_desktop() {
  desktop_source=$STATE/browser-current/helium.desktop
  desktop_target=$(browser_desktop_file)
  mkdir -p "$WORK"
  if [ -f "$desktop_source" ]; then
    {
      say "# NIRUX owner: $PREFIX"
      sed -e "s|^Exec=helium|Exec=\"$BIN/helium\"|" \
          -e "s|^Icon=helium\$|Icon=$STATE/browser-current/product_logo_256.png|" \
          "$desktop_source"
    } > "$WORK/helium.desktop"
  else
    {
      say "# NIRUX owner: $PREFIX"
      say '[Desktop Entry]'
      say 'Name=Helium'
      say 'Comment=Access the Internet'
      say 'Type=Application'
      say "Exec=\"$BIN/helium\" %U"
      say "Icon=$STATE/browser-current/product_logo_256.png"
      say 'Terminal=false'
      say 'Categories=Network;WebBrowser;'
      say 'MimeType=application/pdf;application/rdf+xml;application/rss+xml;application/xhtml+xml;text/html;text/xml;x-scheme-handler/http;x-scheme-handler/https;'
    } > "$WORK/helium.desktop"
  fi
  write_prefix_file "$desktop_target" "$WORK/helium.desktop"
}
browser_remove_managed() {
  remove_prefix_file "$(browser_desktop_file)"
  if [ -L "$BIN/helium" ]; then
    case "$(readlink "$BIN/helium")" in
      "$STATE/browser-current/helium"|"$STATE/browsers"/*) rm -f "$BIN/helium" ;;
    esac
  elif browser_launcher_owned "$BIN/helium"; then
    rm -f "$BIN/helium"
  fi
  rm -rf "$STATE/browser-current" "$STATE/browsers"
  rm -f "$STATE/helium-flags"
}
browser_remove_policy() {
  rm -f "$STATE/browser-policy"
}
browser_verify_archive() {
  [ -f "$1" ] || die "Helium archive is missing: $1"
  case "$HELIUM_SHA256" in
    *[!0-9a-fA-F]*|'') die 'Helium checksum is invalid' ;;
  esac
  [ "${#HELIUM_SHA256}" = 64 ] || die 'Helium checksum is invalid'
  actual=$(sha256sum "$1" | cut -d ' ' -f1)
  [ "$actual" = "$HELIUM_SHA256" ] || \
    die "Helium checksum mismatch; current browser kept"
}
browser_install_archive() {
  archive=$1
  [ -n "${WORK:-}" ] || die 'browser installation requires a working directory'
  browser_verify_archive "$archive"
  unpack=$WORK/helium-unpack
  rm -rf "$unpack"
  mkdir -p "$unpack" || die 'could not create the Helium extraction directory'
  tar -xJf "$archive" -C "$unpack" || die 'could not extract the Helium archive'
  top=$unpack/helium-$HELIUM_VERSION-x86_64_linux
  [ -x "$top/helium" ] || die 'Helium archive is missing the executable'
  load_output=$(LD_TRACE_LOADED_OBJECTS=1 "$top/helium" 2>&1 || :)
  missing_libs=$(printf '%s\n' "$load_output" | awk '/not found/ {print $1}' | sort -u)
  if [ -n "$missing_libs" ]; then
    die "Helium needs missing shared libraries: $(printf '%s' "$missing_libs" | tr '\n' ' ')"
  fi
  reported=$("$top/helium" --version 2>&1) || die 'the extracted Helium executable cannot start'
  case "$reported" in
    *"$HELIUM_VERSION"*) ;;
    *) die "Helium reports an unexpected version: $reported" ;;
  esac
  mkdir -p "$STATE/browsers" || die 'could not create the managed browser directory'
  destination=$STATE/browsers/helium-$HELIUM_VERSION
  staging=$STATE/browsers/.helium-$HELIUM_VERSION.$$
  rm -rf "$staging"
  mv "$top" "$staging" || die 'could not stage the Helium files'
  rm -rf "$destination"
  mv "$staging" "$destination" || die 'could not install the Helium files'
  mkdir -p "$BIN" || die 'could not create the command directory'
  ln -s "$destination" "$STATE/.browser-current.$$" || die 'could not link Helium'
  mv -Tf "$STATE/.browser-current.$$" "$STATE/browser-current" || die 'could not activate Helium'
  browser_write_launcher
  app_prune_versions "$STATE/browsers" "$destination" Helium "$HELIUM_VERSION"
  rm -rf "$unpack"
  browser_write_desktop
  say "Installed managed Helium $HELIUM_VERSION"
}
# ── Old app versions: never removed while they run ─────────────────────────
# A running program keeps its files open by path: Helium starts a new helper
# process (the camera, a GPU or audio service, a new renderer) from its own
# directory long after it started. Removing the directory of the version that
# runs broke the camera in Teams until Helium was restarted, so an old
# version stays until nothing runs from it; a later update removes it.
#
# The processes of this user whose program lies under directory $1, as PIDs
# (also a program whose file is already deleted). NIRUX_PROC is for tests.
app_dir_running() {
  ad_dir=$(cd "$1" 2>/dev/null && pwd -P) || return 0
  for ad_exe in "${NIRUX_PROC:-/proc}"/[0-9]*/exe; do
    ad_target=$(readlink "$ad_exe" 2>/dev/null) || continue
    case "$ad_target" in
      "$ad_dir"/*|"$1"/*) ad_pid=${ad_exe%/exe}; say "${ad_pid##*/}" ;;
    esac
  done
}
# Tell the running session that APP ($1) must be restarted to use version
# $2, through NIRUNOTIFY, also when the update runs over SSH or at night (the
# session bus of this user is used when the environment has none).
app_restart_notice() {
  command -v notify-send >/dev/null 2>&1 || return 0
  an_bus=${DBUS_SESSION_BUS_ADDRESS:-}
  if [ -z "$an_bus" ] && [ -S "${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/bus" ]; then
    an_bus=unix:path=${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/bus
  fi
  [ -n "$an_bus" ] || return 0
  DBUS_SESSION_BUS_ADDRESS=$an_bus timeout 5 notify-send -a NIRUX \
    "Restart $1 to finish its update" \
    "$1 $2 is installed. The $1 that runs now keeps working until you close all its windows and open it again." \
    >/dev/null 2>&1 || :
}
# Remove the old versions under directory $1 except $2 (the new one) and
# links. A version that runs stays; APP ($3) and its new VERSION ($4) are
# named in the message and the notice.
app_prune_versions() {
  ap_notice=
  for ap_old in "$1"/*; do
    [ -d "$ap_old" ] || continue
    [ -L "$ap_old" ] && continue
    [ "$ap_old" = "$2" ] && continue
    if [ -n "$(app_dir_running "$ap_old" | head -n 1)" ]; then
      say "Keeping ${ap_old##*/} while it runs; restart $3 to use $4 (a later update removes the old one)."
      ap_notice=1
      continue
    fi
    rm -rf "$ap_old"
  done
  [ -z "$ap_notice" ] || app_restart_notice "$3" "$4"
}
browser_install() {
  [ "${BROWSER_EFFECTIVE:-keep}" = helium ] || return 0
  if external=$(browser_unmanaged); then
    say "Using the existing Helium at $external; NIRUX will not overwrite it."
    return 0
  fi
  installed=
  if browser_managed; then installed=$(browser_installed_version || :); fi
  [ -n "${WORK:-}" ] || die 'browser installation requires a working directory'
  mkdir -p "$WORK/download/helium" || die 'could not create the Helium download directory'
  # The newest upstream release, when it is newer than the pin and verified.
  if app_upstream helium "$HELIUM_VERSION"; then
    if [ -n "$installed" ] && version_at_least "$installed" "$AL_VERSION"; then
      browser_write_launcher
      browser_write_desktop
      say "Managed Helium $installed is current"
      return 0
    fi
    bi_version=$AL_VERSION
    bi_archive=$WORK/download/helium/helium-$bi_version-x86_64_linux.tar.xz
    say "Downloading Helium $bi_version (newest upstream release)"
    if fetch "https://github.com/imputnet/helium-linux/releases/download/$bi_version/helium-$bi_version-x86_64_linux.tar.xz" "$bi_archive" &&
       app_digest_ok "$bi_archive" "$AL_DIGEST" &&
       ( SUDO_SECRET_BORROWED=1 HELIUM_VERSION=$bi_version HELIUM_SHA256=${AL_DIGEST#sha256:}
         browser_install_archive "$bi_archive" ); then
      return 0
    fi
    say "nirux: Helium $bi_version could not be downloaded or verified; using the pinned version instead." >&2
  fi
  if [ -n "$installed" ] && version_at_least "$installed" "$HELIUM_VERSION"; then
    browser_write_launcher
    browser_write_desktop
    if [ "$installed" = "$HELIUM_VERSION" ]; then say "Managed Helium $HELIUM_VERSION is already installed"
    else say "Keeping managed Helium $installed (the minimum is $HELIUM_VERSION)"; fi
    return 0
  fi
  archive=$WORK/download/helium/helium-$HELIUM_VERSION-x86_64_linux.tar.xz
  say "Downloading Helium $HELIUM_VERSION"
  fetch "https://github.com/imputnet/helium-linux/releases/download/$HELIUM_VERSION/helium-$HELIUM_VERSION-x86_64_linux.tar.xz" "$archive"
  browser_install_archive "$archive"
}
# ── Hardware video decoding in Helium (docs: manual chapter 11) ─────────────
# Helium (Chromium 157) decodes video on the CPU on X11 unless it uses VA-API.
# Its default OpenGL path selects the VA-API decoder and then falls back to
# software on AMD (measured on a Radeon RX 6600); the Vulkan path decodes on the
# GPU. So, for the GPU that drives the display, NIRUX installs the VA-API
# driver, vainfo and the Mesa Vulkan driver, checks that the render node really
# reports decode profiles and that Vulkan sees the same GPU, and only then
# writes $STATE/helium-flags for the launcher. Chromium still falls back to its
# software decoders for a codec the GPU cannot decode. No root is needed except
# for the packages, which go through install_packages (or the nightly helper).
#
# ~/.config/nirux/browser.toml, [browser] hardware_video:
#   auto  AMD and Intel on, NVIDIA off (the default; also when the file is absent)
#   on    also NVIDIA (proprietary driver with nvidia-vaapi-driver; experimental)
#   off   never; Helium starts exactly as upstream does
# The setting lives in a NIRUX-only file because NIRUWM and NIRUBAR refuse
# unknown keys in the shared config.toml.
HWVIDEO_FEATURES=Vulkan,VulkanFromANGLE,DefaultANGLEVulkan,VaapiIgnoreDriverChecks
hwvideo_config() { say "$NIRUX_CONFIG/browser.toml"; }
hwvideo_mode() {
  hv_value=$(toml_value "$(hwvideo_config)" browser hardware_video)
  case "$hv_value" in
    ''|auto) say auto ;;
    on|off) say "$hv_value" ;;
    *) say "nirux: [browser] hardware_video = \"$hv_value\" is not auto, on or off; using auto" >&2; say auto ;;
  esac
}
hwvideo_vendor_name() {
  case "$1" in 0x1002) say AMD ;; 0x8086) say Intel ;; 0x10de) say NVIDIA ;; *) say "vendor $1" ;; esac
}
# The GPU Helium should decode on: the one the firmware used for the console
# (boot_vga), else one with a connected display, else an integrated (not
# NVIDIA) one, else the first. Only DRM devices with a render node count.
# Sets HV_GPUS, HV_VID, HV_DID, HV_DRIVER, HV_RENDER and HV_PCI.
hwvideo_detect() {
  HV_GPUS=0; HV_VID=; HV_DID=; HV_DRIVER=; HV_RENDER=; HV_PCI=
  hv_best=-1
  for hv_card in "${NIRUX_SYSFS_DRM:-/sys/class/drm}"/card*; do
    case "${hv_card##*/}" in card|card*[!0-9]*) continue ;; esac
    hv_dev=$hv_card/device
    [ -r "$hv_dev/vendor" ] || continue
    hv_render=
    for hv_r in "$hv_dev"/drm/renderD*; do
      [ -e "$hv_r" ] && hv_render=${hv_r##*/} && break
    done
    [ -n "$hv_render" ] || continue
    HV_GPUS=$((HV_GPUS + 1))
    hv_vid=$(tr 'A-F' 'a-f' < "$hv_dev/vendor" 2>/dev/null)
    hv_score=0
    [ "$(cat "$hv_dev/boot_vga" 2>/dev/null)" = 1 ] && hv_score=$((hv_score + 4))
    for hv_st in "$hv_card"-*/status; do
      if [ "$(cat "$hv_st" 2>/dev/null)" = connected ]; then hv_score=$((hv_score + 2)); break; fi
    done
    [ "$hv_vid" = 0x10de ] || hv_score=$((hv_score + 1))
    [ "$hv_score" -gt "$hv_best" ] || continue
    hv_best=$hv_score
    HV_VID=$hv_vid; HV_RENDER=$hv_render
    HV_DID=$(tr 'A-F' 'a-f' < "$hv_dev/device" 2>/dev/null)
    HV_DRIVER=; [ ! -L "$hv_dev/driver" ] || HV_DRIVER=$(basename "$(readlink "$hv_dev/driver")")
    HV_PCI=; [ ! -L "$hv_dev" ] || HV_PCI=$(basename "$(readlink "$hv_dev")")
  done
  [ "$HV_GPUS" -gt 0 ]
}
# Can this GPU and driver use the Vulkan VA-API path in MODE? Sets HV_REASON.
hwvideo_supported() {
  HV_REASON=
  [ "$1" != off ] || { HV_REASON='turned off in ~/.config/nirux/browser.toml'; return 1; }
  case "$HV_VID:$HV_DRIVER" in
    0x1002:amdgpu|0x8086:i915|0x8086:xe) return 0 ;;
    0x1002:*) HV_REASON="the $HV_DRIVER kernel driver has no Vulkan video path (needs amdgpu)" ;;
    0x10de:nvidia)
      [ "$1" = on ] && return 0
      HV_REASON='NVIDIA is off by default (set hardware_video = "on" to try nvidia-vaapi-driver)' ;;
    0x10de:*) HV_REASON="the $HV_DRIVER driver has no working video decoding for Chromium" ;;
    *) HV_REASON="no supported GPU (AMD, Intel or NVIDIA) drives the display" ;;
  esac
  return 1
}
# Distribution packages for VENDOR (amd, intel, nvidia or all, for the nightly
# update's allowlist): the VA-API driver, vainfo, the Mesa Vulkan driver,
# vulkaninfo and the Mesa device-select layer that pins Vulkan to one GPU.
hwvideo_packages_for() {
  case "$1" in
    debian)
      say vainfo vulkan-tools mesa-vulkan-drivers
      case "$2" in amd) say mesa-va-drivers ;; intel) say intel-media-va-driver ;; nvidia) say nvidia-vaapi-driver ;;
        all) say mesa-va-drivers intel-media-va-driver nvidia-vaapi-driver ;; esac ;;
    arch)
      say libva-utils vulkan-tools vulkan-mesa-implicit-layers
      case "$2" in amd) say mesa vulkan-radeon ;; intel) say intel-media-driver vulkan-intel ;; nvidia) say libva-nvidia-driver ;;
        all) say mesa vulkan-radeon intel-media-driver vulkan-intel libva-nvidia-driver ;; esac ;;
    void)
      say libva-utils Vulkan-Tools mesa-vulkan-overlay-layer
      case "$2" in amd) say mesa-vaapi mesa-vulkan-radeon ;; intel) say intel-media-driver mesa-vulkan-intel ;; nvidia) say nvidia-vaapi-driver ;;
        all) say mesa-vaapi mesa-vulkan-radeon intel-media-driver mesa-vulkan-intel nvidia-vaapi-driver ;; esac ;;
  esac
}
hwvideo_vendor() {
  case "$HV_VID" in 0x1002) say amd ;; 0x8086) say intel ;; 0x10de) say nvidia ;; esac
}
hwvideo_missing_packages() {
  # distribution_package_present asks the package database of $OS.
  [ -n "${OS:-}" ] || OS=$1
  # shellcheck disable=SC2046 # fixed package names, one per word
  for hv_pkg in $(hwvideo_packages_for "$1" "$(hwvideo_vendor)"); do
    distribution_package_present "$hv_pkg" || say "$hv_pkg"
  done
  return 0
}
hwvideo_bounded() {
  if command -v timeout >/dev/null 2>&1; then timeout 20 "$@"; else "$@"; fi
}
hwvideo_vainfo() {
  if [ "$HV_VID" = 0x10de ]; then
    LIBVA_DRIVER_NAME=nvidia NVD_BACKEND=direct hwvideo_bounded vainfo --display drm --device "$1"
  else
    hwvideo_bounded vainfo --display drm --device "$1"
  fi
}
# Does the render node decode, and does Vulkan see the same GPU? Sets
# HV_PROFILES (decodable codecs) and HV_REASON. Runs as the user.
hwvideo_verify() {
  HV_PROFILES=; HV_REASON=
  hv_node=${NIRUX_DEV_DRI:-/dev/dri}/$HV_RENDER
  if [ ! -r "$hv_node" ] || [ ! -w "$hv_node" ]; then
    HV_REASON="no access to $hv_node (the seat or the render group grants it)"; return 1
  fi
  command -v vainfo >/dev/null 2>&1 || { HV_REASON='vainfo is not installed'; return 1; }
  hv_out=$(hwvideo_vainfo "$hv_node" 2>/dev/null) || :
  HV_PROFILES=$(printf '%s\n' "$hv_out" | awk '
    /VAEntrypointVLD/ {
      p = $1
      if (p ~ /^VAProfileH264/) c = "H264"; else if (p ~ /^VAProfileVP9/) c = "VP9"
      else if (p ~ /^VAProfileAV1/) c = "AV1"; else if (p ~ /^VAProfileHEVC/) c = "HEVC"
      else if (p ~ /^VAProfileVP8/) c = "VP8"; else next
      if (!(c in seen)) { seen[c] = 1; out = out (out == "" ? "" : " ") c }
    }
    END { print out }')
  if [ -z "$HV_PROFILES" ]; then
    hv_drv=$(printf '%s\n' "$hv_out" | sed -n 's/^vainfo: Driver version: //p' | head -n 1)
    if [ -n "$hv_drv" ]; then HV_REASON="the VA-API driver ($hv_drv) reports no H264/VP9/AV1/HEVC decoding"
    else HV_REASON="no VA-API driver works on $hv_node"; fi
    return 1
  fi
  command -v vulkaninfo >/dev/null 2>&1 || { HV_REASON='vulkaninfo is not installed'; return 1; }
  if ! hwvideo_bounded vulkaninfo --summary 2>/dev/null | tr '[:upper:]' '[:lower:]' | awk -v v="$HV_VID" -v d="$HV_DID" '
      /vendorid *=/ { vid = $NF } /deviceid *=/ { if (vid == v && $NF == d) found = 1 }
      END { exit !found }'; then
    HV_REASON="Vulkan has no driver for this $(hwvideo_vendor_name "$HV_VID") GPU"; return 1
  fi
  if [ "$HV_GPUS" -gt 1 ]; then
    hv_layer=
    for hv_dir in /usr/share/vulkan/implicit_layer.d /etc/vulkan/implicit_layer.d; do
      [ ! -f "${NIRUX_SYSTEM_ROOT:-}$hv_dir/VkLayer_MESA_device_select.json" ] || hv_layer=1
    done
    [ -n "$hv_layer" ] || { HV_REASON='several GPUs and no Mesa device-select layer to keep Vulkan on this one'; return 1; }
  fi
  return 0
}
# The flags file for the launcher. "gpu PCI" makes the launcher ignore the file
# when that GPU is gone (an unplugged eGPU), "node" becomes the render node of
# that GPU at start, so a renumbered /dev/dri cannot point VA-API at another GPU.
hwvideo_flags() {
  say '# NIRUX hardware video flags for Helium; written by nirux update, see nirux doctor.'
  say "gpu $HV_PCI"
  say 'arg --use-angle=vulkan'
  if [ "$HV_VID" = 0x10de ]; then say "arg --enable-features=$HWVIDEO_FEATURES,VaapiOnNvidiaGPUs"
  else say "arg --enable-features=$HWVIDEO_FEATURES"; fi
  say node
  [ "$HV_GPUS" -le 1 ] || say "env MESA_VK_DEVICE_SELECT=${HV_VID#0x}:${HV_DID#0x}!"
  if [ "$HV_VID" = 0x10de ]; then say 'env LIBVA_DRIVER_NAME=nvidia'; say 'env NVD_BACKEND=direct'; fi
}
hwvideo_disable() {
  [ ! -e "$STATE/helium-flags" ] || rm -f "$STATE/helium-flags"
}
# Called on install and update, after the browser: install what is missing,
# verify, then write or remove the flags. Never fails the update.
hwvideo_apply() {
  if ! browser_managed; then hwvideo_disable; return 0; fi
  hv_mode=$(hwvideo_mode)
  if ! hwvideo_detect; then
    hwvideo_disable; say 'Hardware video in Helium: off (no GPU with a render node)'; return 0
  fi
  if ! hwvideo_supported "$hv_mode"; then
    hwvideo_disable; say "Hardware video in Helium: off ($HV_REASON)"; return 0
  fi
  # The nightly run never turns the flags on for the first time: a change in
  # how Helium draws must first happen in front of the owner (nirux update or
  # nirux doctor --fix). Once on, the nightly run keeps them current.
  if [ "${NIRUX_AUTO:-0}" = 1 ] && [ ! -f "$STATE/helium-flags" ]; then
    say 'Hardware video in Helium: available, not on yet (turn it on with nirux update or nirux doctor --fix)'
    return 0
  fi
  hv_os=${OS:-$( (distro) 2>/dev/null || :)}
  hv_missing=$(hwvideo_missing_packages "$hv_os" | tr '\n' ' ' | sed 's/ $//')
  if [ -n "$hv_missing" ]; then
    if [ "${packages:-1}" = 0 ]; then
      say "Hardware video packages not installed (--no-packages): $hv_missing"
    elif [ "${NIRUX_AUTO:-0}" = 1 ]; then
      # shellcheck disable=SC2086 # fixed package names, one per word
      auto_want_packages $hv_missing
    elif ! ( SUDO_SECRET_BORROWED=1; install_packages "$hv_missing" ); then
      say "nirux: could not install the hardware video packages: $hv_missing" >&2
    fi
  fi
  if ! hwvideo_verify; then
    hwvideo_disable; say "Hardware video in Helium: off ($HV_REASON)"; return 0
  fi
  mkdir -p "$STATE" || return 0
  hwvideo_flags > "$STATE/.helium-flags.$$" || { rm -f "$STATE/.helium-flags.$$"; return 0; }
  if [ -f "$STATE/helium-flags" ] && same_file "$STATE/.helium-flags.$$" "$STATE/helium-flags"; then
    rm -f "$STATE/.helium-flags.$$"
  else
    mv -f "$STATE/.helium-flags.$$" "$STATE/helium-flags" || { rm -f "$STATE/.helium-flags.$$"; return 0; }
  fi
  say "Hardware video in Helium: on ($(hwvideo_vendor_name "$HV_VID") $HV_DRIVER, $HV_PROFILES; restart Helium to use it)"
}
hwvideo_doctor() {
  hv_mode=$(hwvideo_mode)
  if ! hwvideo_detect; then say 'hardware video: no GPU with a render node'; return 0; fi
  hv_more=; [ "$HV_GPUS" -le 1 ] || hv_more=", 1 of $HV_GPUS GPUs"
  say "hardware video: GPU $(hwvideo_vendor_name "$HV_VID") ${HV_DID:-} ($HV_DRIVER, $HV_PCI, /dev/dri/$HV_RENDER$hv_more), setting $hv_mode"
  if ! hwvideo_supported "$hv_mode"; then
    say "hardware video: Helium flags off: $HV_REASON"; hwvideo_disable_note; return 0
  fi
  hv_os=$( (distro) 2>/dev/null || :)
  hv_missing=$(hwvideo_missing_packages "$hv_os" | tr '\n' ' ' | sed 's/ $//')
  [ -z "$hv_missing" ] || say "hardware video: missing packages: $hv_missing"
  if hwvideo_verify; then
    say "hardware video: VA-API ok, decodes $HV_PROFILES; Vulkan sees the GPU"
  else
    say "hardware video: not ready: $HV_REASON"
  fi
  if ! browser_managed; then
    say 'hardware video: Helium is not managed by NIRUX, so its flags are not set'
  elif [ -s "$STATE/helium-flags" ]; then
    say "hardware video: Helium flags enabled ($(sed -n 's/^arg //p' "$STATE/helium-flags" | tr '\n' ' ' | sed 's/ $//'))"
  elif [ -z "$HV_REASON" ]; then
    say 'hardware video: Helium flags not written yet (nirux doctor --fix or nirux update)'; doctor_offer hwvideo
  else
    say "hardware video: Helium flags off: $HV_REASON"
  fi
  if [ -n "$hv_missing" ] && browser_managed; then doctor_offer hwvideo; fi
  return 0
}
hwvideo_disable_note() {
  [ ! -s "$STATE/helium-flags" ] || say 'hardware video: an old flags file is still there; nirux update removes it'
}
