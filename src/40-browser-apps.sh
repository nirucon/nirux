opencode_install() {
  # OpenCode is a managed external CLI, with no service, agent or auth setup.
  [ "${NIRUX_TEST_AS_ROOT:-0}" = 1 ] && return 0
  [ -z "$ROOT" ] || return 0
  if command -v opencode >/dev/null 2>&1 && ! opencode_managed; then
    say "Using the existing OpenCode at $(command -v opencode); NIRUX will not overwrite it."
    return 0
  fi
  oc_installed=
  [ ! -x "$STATE/opencode/current/opencode" ] || oc_installed=$(opencode_installed_version || :)
  [ -n "${WORK:-}" ] || die 'OpenCode installation requires a working directory'
  mkdir -p "$WORK/download/opencode" || die 'could not create the OpenCode download directory'
  # OpenCode 2's newest release, the version opencode.ai's installer picks,
  # from the npm registry that publishes its sha512.
  if app_upstream opencode "$OPENCODE_VERSION" &&
     { [ -z "$oc_installed" ] || ! version_at_least "$oc_installed" "$AL_VERSION"; }; then
    oc_up=$AL_VERSION
    oc_scope=${AL_EXTRA:-@opencode}
    oc_archive=$WORK/download/opencode/cli-linux-x64-$oc_up.tgz
    say "Downloading OpenCode $oc_up (newest upstream release)"
    if fetch "https://registry.npmjs.org/$oc_scope/cli-linux-x64/-/cli-linux-x64-$oc_up.tgz" "$oc_archive" &&
       app_digest_ok "$oc_archive" "$AL_DIGEST" &&
       ( SUDO_SECRET_BORROWED=1; opencode_install_archive "$oc_archive" "$oc_up" npm ); then
      return 0
    fi
    say "nirux: OpenCode $oc_up could not be downloaded or verified; using the pinned version instead." >&2
  fi
  if [ -n "$oc_installed" ] && version_at_least "$oc_installed" "$OPENCODE_VERSION"; then
    mkdir -p "$BIN" || die 'could not create the command directory'
    ln -sfn "$STATE/opencode/current/opencode" "$BIN/opencode" || die 'could not link OpenCode'
    say "Managed OpenCode $oc_installed is already installed"
    return 0
  fi
  archive=$WORK/download/opencode/opencode-linux-x64.tar.gz
  say "Downloading OpenCode $OPENCODE_VERSION"
  fetch "https://opencode.ai/files/bin/$OPENCODE_VERSION/opencode-linux-x64.tar.gz" "$archive"
  actual=$(sha256sum "$archive" | cut -d ' ' -f1)
  [ "$actual" = "$OPENCODE_SHA256" ] || die 'OpenCode checksum mismatch; current installation kept'
  opencode_install_archive "$archive" "$OPENCODE_VERSION" tar
}
# Install a verified OpenCode ARCHIVE of VERSION; FORMAT tar (opencode.ai) or npm.
opencode_install_archive() {
  archive=$1 oc_version=$2 oc_format=$3
  unpack=$WORK/opencode-unpack
  rm -rf "$unpack"
  mkdir -p "$unpack" || die 'could not create the OpenCode extraction directory'
  tar -xzf "$archive" -C "$unpack" || die 'could not extract the OpenCode archive'
  # The npm package keeps the program in package/bin.
  if [ "$oc_format" = npm ]; then
    [ -f "$unpack/package/bin/opencode" ] && [ ! -L "$unpack/package/bin/opencode" ] ||
      die 'OpenCode package is missing the executable'
    mv "$unpack/package/bin/opencode" "$unpack/opencode.bin" && rm -rf "$unpack/package" &&
      mv "$unpack/opencode.bin" "$unpack/opencode" || die 'could not unpack the OpenCode package'
    chmod 755 "$unpack/opencode" || die 'could not unpack the OpenCode package'
  fi
  [ -x "$unpack/opencode" ] || die 'OpenCode archive is missing the executable'
  load_output=$(LD_TRACE_LOADED_OBJECTS=1 "$unpack/opencode" 2>&1 || :)
  missing_libs=$(printf '%s\n' "$load_output" | awk '/not found/ {print $1}' | sort -u)
  [ -z "$missing_libs" ] || die "OpenCode needs missing shared libraries: $(printf '%s' "$missing_libs" | tr '\n' ' ')"
  reported=$("$unpack/opencode" --version 2>&1) || die 'the extracted OpenCode executable cannot start'
  case "$reported" in
    *"$oc_version"*) ;;
    *) die "OpenCode reports an unexpected version: $reported" ;;
  esac
  destination=$STATE/opencode/$oc_version
  staging=$STATE/opencode/.$oc_version.$$
  mkdir -p "$STATE/opencode" || die 'could not create the OpenCode directory'
  rm -rf "$staging"
  mv "$unpack" "$staging" || die 'could not stage the OpenCode files'
  rm -rf "$destination"
  mv "$staging" "$destination" || die 'could not install the OpenCode files'
  rm -f "$STATE/opencode/current"
  ln -s "$destination" "$STATE/opencode/current" || die 'could not activate OpenCode'
  mkdir -p "$BIN" || die 'could not create the command directory'
  ln -sfn "$STATE/opencode/current/opencode" "$BIN/opencode" || die 'could not link OpenCode'
  printf '%s\n' "$oc_version" > "$STATE/opencode-version"
  app_prune_versions "$STATE/opencode" "$destination" OpenCode "$oc_version"
  say "Installed managed OpenCode $oc_version"
}

